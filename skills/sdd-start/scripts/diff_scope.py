#!/usr/bin/env python3
# sdd-playbook: 0.30.0
"""Check the diff of a task branch against the task, the forbidden zones and the locked tests.

Usage:
  python scripts/diff_scope.py docs/specs/<id> --task T-01 [--base main] [--strict]
  python scripts/diff_scope.py docs/specs/<id> [--base main] [--strict]        # the whole branch, all the tasks

The diff is computed from the merge-base with --base (default: the first of main, master, origin/main, origin/master)
and includes uncommitted changes and untracked files; generated files (__pycache__/, *.pyc, reports/) do not count.
AGENTS.md is read from the merge-base when it exists there: the branch cannot loosen it.
- Forbidden zones: paths of the "- Do not modify: a, b" lines of AGENTS.md -> error (exit 1).
- Locked tests: the test files of a commit with the trailer "Test-Lock: T-nn" (the red tests written from the ACs)
  cannot change in a later commit without the same trailer, nor in uncommitted changes -> error (exit 1).
- Outside the task: changed files not in the task's "files:" (all the tasks without --task), excluding the spec
  folder, docs/system/, docs/bugs/, docs/adr/ and the process tooling -> warning (error with --strict).
- Sensitive areas: files in the "- Sensitive areas: a, b" lines of AGENTS.md -> "SENSITIVE" line, to copy into the PR
  description: the human reads the diff of those files before the merge. Not an error.
- Dependencies: a changed manifest or lockfile -> warning (a new dependency is an "Asks first" decision).
- Size: more than 400 changed lines outside tests and docs -> warning (a PR to read in 15-30 minutes).
Exit code: 0 ok; 1 violations; 2 wrong usage or git not usable. Standard library + git only.
"""
from __future__ import annotations

import fnmatch
import re
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ in the project: it would count as a changed file
sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec_lint  # noqa: E402

ALWAYS_ALLOWED = ("docs/system/", "docs/bugs/", "docs/adr/")
TEST_LOCK = re.compile(r"^Test-Lock:\s*(\S+)", re.M)
NOISE = re.compile(r"(^|/)(__pycache__|\.pytest_cache|reports)/|\.py[co]$")  # files generated by the tools
TEST_DIRS = {"tests", "test", "__tests__", "spec"}
TEST_NAME = re.compile(r"(^test_.*|.*_test|.*[._](test|spec)|.*Tests?)\.\w+$")
MANIFEST = {"package.json", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "pyproject.toml", "uv.lock",
            "poetry.lock", "Pipfile", "Pipfile.lock", "setup.py", "setup.cfg", "go.mod", "go.sum", "Cargo.toml",
            "Cargo.lock", "pom.xml", "build.gradle", "build.gradle.kts", "packages.lock.json",
            "Directory.Packages.props", "Gemfile", "Gemfile.lock", "composer.json", "composer.lock"}
MANIFEST_GLOB = ("requirements*.txt", "*.csproj", "*.fsproj", "*.vbproj")
MAX_LINES = 400  # beyond this, the PR is hard to read in one sitting (warning)
# Process tooling: it serves the playbook, not the product, so it is never "outside the task" nor counted in the size.
SDD_SCRIPTS = {"verify.py", "state.py", "spec_lint.py", "trace_check.py", "diff_scope.py", "docs_check.py",
               "scan_repo.py", "secrets_check.py"}
TOOLING_FILES = {"AGENTS.md", "CLAUDE.md", ".gitattributes", ".gitignore", ".secrets-ignore"}
TOOLING_DIRS = (".github/", ".vscode/")


def git(*args: str) -> tuple[int, str]:
    r = subprocess.run(["git", "-c", "core.quotePath=false", *args], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")  # quotePath: non-ASCII paths as they are
    return r.returncode, r.stdout.strip()


def normalize(path: str) -> str:
    """Forward slashes and no "./" prefix (the leading dot of ".github/" is kept)."""
    return re.sub(r"^(\./)+", "", path.replace("\\", "/").strip())


def matches(path: str, pattern: str) -> bool:
    p, pat = normalize(path), normalize(pattern)
    if not pat:
        return False
    if any(c in pat for c in "*?["):
        return fnmatch.fnmatch(p, pat)
    return p == pat or p.startswith(pat.rstrip("/") + "/")


def raw_entries(agents: str, name: str) -> list[str]:
    entries = []
    for m in re.finditer(rf"^\s*[-*]\s+{name}\s*:\s*(.*)$", agents, re.M | re.I):
        entries += [v.strip() for v in re.split(r"[,;]", re.sub(r"<[^<>\n]*>", "", m.group(1)))]
    return [v for v in entries if v]


def entry_path(entry: str) -> str | None:
    """Path of an entry: text in backticks or first word, if it looks like a path."""
    m = re.match(r"`([^`]+)`|(\S+)", entry)
    v = (m.group(1) or m.group(2)).strip() if m else ""
    return v if v and ("/" in v or "." in v or any(c in v for c in "*?[")) else None


def agents_entries(agents: str, name: str) -> list[str]:
    """Paths of all the "- <name>: a, b" lines of AGENTS.md (first word or text in backticks)."""
    return [p for v in raw_entries(agents, name) if (p := entry_path(v))]


def non_path_entries(agents: str) -> list[str]:
    return [v for name in ("Do not modify", "Sensitive areas") for v in raw_entries(agents, name)
            if entry_path(v) is None]


def forbidden_paths(agents: str) -> list[str]:
    return agents_entries(agents, "Do not modify")


def is_manifest(path: str) -> bool:
    name = normalize(path).split("/")[-1]
    return name in MANIFEST or any(fnmatch.fnmatch(name, g) for g in MANIFEST_GLOB)


def is_test(path: str) -> bool:
    pieces = normalize(path).split("/")
    return bool(TEST_DIRS & set(pieces[:-1])) or bool(TEST_NAME.match(pieces[-1]))


def is_tooling(path: str) -> bool:
    p = normalize(path)
    return (p in TOOLING_FILES or p.startswith(TOOLING_DIRS)
            or (p.startswith("scripts/") and p.count("/") == 1 and p.split("/")[1] in SDD_SCRIPTS))


def is_production(path: str) -> bool:
    p = normalize(path)
    return not (is_test(p) or p.startswith("docs/") or p.lower().endswith(".md") or NOISE.search(p) or is_tooling(p))


def base_ref(explicit: str | None) -> str | None:
    for ref in ([explicit] if explicit else ["main", "master", "origin/main", "origin/master"]):
        if git("rev-parse", "--verify", "--quiet", ref)[0] == 0:
            return ref
    return None


def merge_base(base: str) -> str:
    code, mb = git("merge-base", "HEAD", base)
    if code != 0:
        raise RuntimeError("cannot compute the merge-base")
    return mb


def untracked() -> list[str]:
    _, new = git("ls-files", "--others", "--exclude-standard")
    return [f for f in new.splitlines() if f.strip() and not NOISE.search(f)]


def uncommitted() -> list[str]:
    _, diff = git("diff", "--name-only", "--no-renames", "HEAD")
    return [f for f in diff.splitlines() if f.strip()] + untracked()


def changed_files(mb: str) -> list[str]:
    """Files touched since the merge-base: --no-renames also reports the source path of a rename."""
    _, diff = git("diff", "--name-only", "--no-renames", mb)
    return sorted({f for f in diff.splitlines() if f.strip()} | set(untracked()))


def from_base(mb: str, path: str) -> str | None:
    """Content of the file at the merge-base, None if it does not exist there."""
    code, text = git("show", f"{mb}:{normalize(path)}")
    return text if code == 0 else None


def branch_commits(mb: str) -> list[tuple[str, str | None, list[str]]]:
    """(sha, task of the Test-Lock trailer or None, files touched) from oldest to newest."""
    _, shas = git("rev-list", "--reverse", f"{mb}..HEAD")
    out = []
    for sha in shas.split():
        _, body = git("show", "-s", "--format=%B", sha)
        _, files = git("diff-tree", "--no-commit-id", "--name-only", "--no-renames", "-r", "--root", sha)
        m = TEST_LOCK.search(body)
        out.append((sha, m.group(1) if m else None, [f for f in files.splitlines() if f.strip()]))
    return out


def locked_tests(commits: list[tuple[str, str | None, list[str]]], dirty: list[str]):
    """Return (locked files, violations, non-test files in Test-Lock commits)."""
    locked: set[str] = set()
    violations, non_test = [], []
    for sha, lock, files in commits:
        if lock:
            for f in files:
                if is_test(f):
                    locked.add(f)
                else:
                    non_test.append(f"{f} ({sha[:7]})")
            continue
        violations += [f"{f} (commit {sha[:7]})" for f in files if f in locked]
    violations += [f"{f} (uncommitted)" for f in dirty if f in locked]
    return sorted(locked), violations, non_test


def changed_lines(mb: str) -> int:
    """Lines added and removed outside tests, docs and tooling (untracked files count with all their lines)."""
    _, stat = git("diff", "--numstat", "--no-renames", mb)
    total = 0
    for line in stat.splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and parts[0].isdigit() and is_production(parts[2]):
            total += int(parts[0]) + int(parts[1])
    for f in untracked():
        if is_production(f) and Path(f).is_file():
            total += len(Path(f).read_text(encoding="utf-8", errors="ignore").splitlines())
    return total


def task_scope(feature: Path, tid: str | None) -> tuple[list[str], str | None]:
    """(files of the task, or of every task without tid; error message)."""
    plan_p = feature / "plan.md"
    plan = plan_p.read_text(encoding="utf-8") if plan_p.is_file() else ""
    tasks = spec_lint.parse_tasks(plan)
    if tid is not None:
        t = next((x for x in tasks if x["id"] == tid), None)
        if t is None:
            return [], f"{tid} not found in {plan_p.as_posix()}"
        return t["files"], None
    return list(dict.fromkeys(f for t in tasks for f in t["files"])), None


def main(argv: list[str]) -> int:
    values = {o: argv[argv.index(o) + 1] for o in ("--base", "--task") if o in argv and argv.index(o) + 1 < len(argv)}
    args = [a for a in argv if not a.startswith("--") and a not in values.values()]
    if not args:
        print(__doc__)
        return 2
    feature = Path(args[0])
    if not feature.is_dir():
        print(f"[ERROR] folder not found: {feature}")
        return 2
    if git("rev-parse", "--is-inside-work-tree")[0] != 0:
        print("[ERROR] not a git repository")
        return 2
    base = base_ref(values.get("--base"))
    if base is None:
        print("[ERROR] no base ref found (main, master, origin/main, origin/master): use --base <ref>")
        return 2
    try:
        mb = merge_base(base)
    except RuntimeError as e:
        print(f"[ERROR] {e}")
        return 2
    scope, problem = task_scope(feature, values.get("--task"))
    if problem:
        print(f"[ERROR] {problem}")
        return 2
    changed = changed_files(mb)
    agents = from_base(mb, "AGENTS.md")
    if agents is None:
        agents = Path("AGENTS.md").read_text(encoding="utf-8") if Path("AGENTS.md").is_file() else ""
    violations = [f for f in changed if any(matches(f, v) for v in forbidden_paths(agents))]
    allowed = ALWAYS_ALLOWED + (f"docs/specs/{feature.name}/",)
    outside = [f for f in changed if f not in violations and not normalize(f).startswith(allowed) and not is_tooling(f)
               and not any(matches(f, p) for p in scope)]
    sensitive = [f for f in changed if any(matches(f, s) for s in agents_entries(agents, "Sensitive areas"))]
    manifests = [f for f in changed if is_manifest(f)]
    locked, touched_tests, non_test = locked_tests(branch_commits(mb), uncommitted())
    lines = changed_lines(mb)
    print(f"Base: {base}; task: {values.get('--task', 'all')}; changed files: {len(changed)}; changed lines: {lines}; "
          f"locked tests: {len(locked)}")
    if "AGENTS.md" in changed:
        print("[WARN] AGENTS.md changed in the branch: forbidden zones and sensitive areas read from the base version")
    for v in non_path_entries(agents):
        print(f"[WARN] AGENTS.md entry that does not look like a path, ignored: '{v}' (use `path/` in backticks)")
    for f in violations:
        print(f"[ERROR] file in a forbidden zone (AGENTS.md): {f}")
    for f in touched_tests:
        print(f"[ERROR] locked test (Test-Lock) changed after locking: {f}")
    for f in non_test:
        print(f"[WARN] non-test file in a Test-Lock commit, not locked: {f}")
    for f in outside:
        print(f"[{'ERROR' if '--strict' in argv else 'WARN'}] file outside the task: {f}")
    for f in manifests:
        print(f"[WARN] dependency manifest or lockfile changed: {f} (a new dependency is asked first; say it in the PR)")
    if lines > MAX_LINES:
        print(f"[WARN] {lines} changed lines outside tests and docs (usually at most {MAX_LINES}): the PR is hard to "
              "read; consider splitting the task")
    if sensitive:
        print(f"SENSITIVE: {', '.join(sensitive)} (read the diff of these files before the merge)")
    ko = bool(violations) or bool(touched_tests) or ("--strict" in argv and bool(outside))
    print("SCOPE: " + ("OK" if not ko else "VIOLATIONS"))
    return 1 if ko else 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):  # UTF-8 even with a cp1252 console (Windows)
        stream.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main(sys.argv[1:]))
