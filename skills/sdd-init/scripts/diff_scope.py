#!/usr/bin/env python3
# sdd-playbook: 0.20.0
"""Compare the changed files with the plan, the forbidden zones and the locked tests.

Usage:
  python scripts/diff_scope.py docs/specs/001-x [--base main] [--strict]

- Forbidden: paths listed in AGENTS.md on the "- Do not modify: a, b" lines -> error (exit 1).
- Out of plan: changed files not listed in plan.md ("Components and files to create/modify" and the "Where" column of
  the "Test strategy" and "Review focus" tables), excluding docs/specs/<this spec>/, docs/system/, docs/bugs/, docs/adr/, docs/glossary.md -> warning (error with
  --strict).
- Locked tests: the test files of a commit with the trailer "Test-Lock: T-nn" (the red tests written from the ACs)
  cannot change in a later commit without the same trailer, nor in uncommitted changes -> error (exit 1). An intended
  fix of the tests goes into a new Test-Lock commit, justified in the review.
- Approved tests: "tests approved: <name, date, sha>" in tasks.md ties the approval to the Test-Lock commit sha; a SHA
  that is not a Test-Lock commit of the branch for that task, or a later Test-Lock commit for the same task, is an
  error (exit 1): the tests changed after the approval and must be approved again.
- Level (playbook §2.1): the level is chosen by the approver; the diff must not break its hard criteria -> error
  (exit 1). A file in the "- Sensitive areas: a, b" lines of AGENTS.md requires L; a change to a dependency manifest or
  lockfile requires at least M. More than 3 production files at level S is a warning (the approver chose S knowing the
  size). Production files exclude tests, docs/, *.md, generated files (__pycache__/, reports/) and the process tooling
  (the playbook scripts in scripts/, AGENTS.md, CLAUDE.md, .github/, .vscode/, .gitattributes, .gitignore,
  .secrets-ignore). A level-S spec has no plan: the plan comparison is skipped.
  AGENTS.md and the level are read from the merge-base when they exist there: the branch cannot loosen them. AGENTS.md
  entries count as paths (first word or text in backticks); the others are reported.
- Dependencies (playbook §8): a changed manifest or lockfile must be in the approved plan (a lockfile counts if the plan
  lists its manifest), or the diff must add a new ADR in docs/adr/ -> otherwise error.
- Planned but not touched: information only.
The diff is computed from the merge-base with --base (default: the first of main, master, origin/main, origin/master)
and includes uncommitted changes and untracked files.
Exit code: 0 ok; 1 violations; 2 wrong usage or git not usable. Standard library + git only.
"""
from __future__ import annotations

import fnmatch
import re
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ in the project: it would count as a changed file
sys.path.insert(0, str(Path(__file__).resolve().parent))
import spec_lint  # noqa: E402

ALWAYS_ALLOWED = ("docs/system/", "docs/bugs/", "docs/adr/", "docs/glossary.md")
PLACEHOLDER = re.compile(r"<[^<>\n]{1,100}>")
PLAN_LINE = re.compile(r"^\s*[-*]\s+(?:`([^`]+)`|([^\s`:]+))")
TEST_LOCK = re.compile(r"^Test-Lock:\s*(\S+)", re.M)
NOISE = re.compile(r"(^|/)(__pycache__|\.pytest_cache|reports)/|\.py[co]$")  # files generated by the tools
LOCKFILE = {"package-lock.json": "package.json", "yarn.lock": "package.json", "pnpm-lock.yaml": "package.json",
            "uv.lock": "pyproject.toml", "poetry.lock": "pyproject.toml", "Pipfile.lock": "Pipfile", "go.sum": "go.mod",
            "Cargo.lock": "Cargo.toml", "Gemfile.lock": "Gemfile", "composer.lock": "composer.json"}
TEST_DIRS = {"tests", "test", "__tests__", "spec"}
TEST_NAME = re.compile(r"(^test_.*|.*_test|.*[._](test|spec)|.*Tests?)\.\w+$")
MANIFEST = {"package.json", "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "pyproject.toml", "uv.lock",
            "poetry.lock", "Pipfile", "Pipfile.lock", "setup.py", "setup.cfg", "go.mod", "go.sum", "Cargo.toml",
            "Cargo.lock", "pom.xml", "build.gradle", "build.gradle.kts", "packages.lock.json",
            "Directory.Packages.props", "Gemfile", "Gemfile.lock", "composer.json", "composer.lock"}
MANIFEST_GLOB = ("requirements*.txt", "*.csproj", "*.fsproj", "*.vbproj")
MAX_FILES_S = 3  # beyond this, level S is a warning: the approver decides
# Process tooling: it serves the playbook, not the product, so it never counts toward the level.
SDD_SCRIPTS = {"verify.py", "state.py", "spec_lint.py", "trace_check.py", "bug_lint.py", "diff_scope.py",
               "docs_check.py", "sync_check.py", "scan_repo.py", "loop.py", "secrets_check.py", "review_package.py",
               "approve.py"}
TOOLING_FILES = {"AGENTS.md", "CLAUDE.md", ".gitattributes", ".gitignore", ".secrets-ignore"}
TOOLING_DIRS = (".github/", ".vscode/")
ORDER = {"S": 0, "M": 1, "L": 2}


def git(*args: str) -> tuple[int, str]:
    r = subprocess.run(["git", "-c", "core.quotePath=false", *args], capture_output=True, text=True,
                       encoding="utf-8", errors="replace")  # quotePath: non-ASCII paths as they are
    return r.returncode, r.stdout.strip()


def normalize(path: str) -> str:
    """Forward slashes and no "./" prefix (the leading dot of ".github/" is kept)."""
    return re.sub(r"^(\./)+", "", path.replace("\\", "/").strip())


def matches(path: str, pattern: str) -> bool:
    p, pat = normalize(path), normalize(pattern)
    if not pat:
        return False
    if any(c in pat for c in "*?["):
        return fnmatch.fnmatch(p, pat)
    return p == pat or p.startswith(pat.rstrip("/") + "/")


def sections(text: str) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    current = None
    for line in text.splitlines():
        if line.startswith("## "):
            current = line[3:].strip()
            out[current] = []
        elif current is not None:
            out[current].append(line)
    return out


def where_paths(lines: list[str]) -> list[str]:
    """Paths of the "Where" column in the test strategy table."""
    out, column = [], None
    for line in lines:
        if not line.strip().startswith("|"):
            continue
        cells = [c.strip().strip("`").strip() for c in line.strip().strip("|").split("|")]
        if column is None:
            column = next((i for i, c in enumerate(cells) if c.lower() == "where"), -1)
            continue
        if column < 0 or column >= len(cells) or set(cells[column]) <= set("-: "):
            continue
        v = cells[column].split("::")[0].strip()
        if v and not PLACEHOLDER.search(v) and " " not in v and ("/" in v or "." in v):
            out.append(v)
    return out


def plan_paths(plan: str) -> list[str]:
    out = []
    for title, lines in sections(plan).items():
        if title.startswith("Components and files"):
            for line in lines:
                m = PLAN_LINE.match(line)
                if m:
                    v = (m.group(1) or m.group(2)).strip()
                    if v and not PLACEHOLDER.search(v):
                        out.append(v)
        elif title.startswith("Test strategy") or title.lower().startswith("review focus"):
            out += where_paths(lines)
    return list(dict.fromkeys(out))


def raw_entries(agents: str, name: str) -> list[str]:
    entries = []
    for m in re.finditer(rf"^\s*[-*]\s+{name}\s*:\s*(.*)$", agents, re.M | re.I):
        entries += [v.strip() for v in re.split(r"[,;]", re.sub(r"<[^<>\n]*>", "", m.group(1)))]
    return [v for v in entries if v]


def entry_path(entry: str) -> str | None:
    """Path of an entry: text in backticks or first word, if it looks like a path."""
    m = re.match(r"`([^`]+)`|(\S+)", entry)
    v = (m.group(1) or m.group(2)).strip() if m else ""
    return v if v and ("/" in v or "." in v or any(c in v for c in "*?[")) else None


def agents_entries(agents: str, name: str) -> list[str]:
    """Paths of all the "- <name>: a, b" lines of AGENTS.md (first word or text in backticks)."""
    return [p for v in raw_entries(agents, name) if (p := entry_path(v))]


def non_path_entries(agents: str) -> list[str]:
    return [v for name in ("Do not modify", "Sensitive areas") for v in raw_entries(agents, name)
            if entry_path(v) is None]


def forbidden_paths(agents: str) -> list[str]:
    return agents_entries(agents, "Do not modify")


def is_manifest(path: str) -> bool:
    name = normalize(path).split("/")[-1]
    return name in MANIFEST or any(fnmatch.fnmatch(name, g) for g in MANIFEST_GLOB)


def is_tooling(path: str) -> bool:
    p = normalize(path)
    return (p in TOOLING_FILES or p.startswith(TOOLING_DIRS)
            or (p.startswith("scripts/") and p.count("/") == 1 and p.split("/")[1] in SDD_SCRIPTS))


def is_production(path: str) -> bool:
    p = normalize(path)
    return not (is_test(p) or p.startswith("docs/") or p.lower().endswith(".md") or NOISE.search(p) or is_tooling(p))


def required_level(changed: list[str], agents: str) -> tuple[str, list[str]]:
    """Minimum level the hard criteria of the diff require, with the reasons (playbook §2.1)."""
    sensitive = agents_entries(agents, "Sensitive areas")
    touched = [f for f in changed if any(matches(f, s) for s in sensitive)]
    if touched:
        return "L", [f"sensitive area (AGENTS.md): {', '.join(touched)}"]
    manifests = [f for f in changed if is_manifest(f)]
    if manifests:
        return "M", [f"dependencies changed: {', '.join(manifests)}"]
    return "S", []


def size_warnings(changed: list[str], declared: str) -> list[str]:
    """Level S with more production files than MAX_FILES_S: a warning, the approver chose the level."""
    production = [f for f in changed if is_production(f)]
    if declared == "S" and len(production) > MAX_FILES_S:
        return [f"level S with {len(production)} production files (usually at most {MAX_FILES_S}): the approver "
                f"chose S; if the change is riskier than its size suggests, raise the level"]
    return []


def is_test(path: str) -> bool:
    pieces = normalize(path).split("/")
    return bool(TEST_DIRS & set(pieces[:-1])) or bool(TEST_NAME.match(pieces[-1]))


def base_ref(explicit: str | None) -> str | None:
    for ref in ([explicit] if explicit else ["main", "master", "origin/main", "origin/master"]):
        if git("rev-parse", "--verify", "--quiet", ref)[0] == 0:
            return ref
    return None


def merge_base(base: str) -> str:
    code, mb = git("merge-base", "HEAD", base)
    if code != 0:
        raise RuntimeError("cannot compute the merge-base")
    return mb


def untracked() -> list[str]:
    _, new = git("ls-files", "--others", "--exclude-standard")
    return [f for f in new.splitlines() if f.strip() and not NOISE.search(f)]


def uncommitted() -> list[str]:
    _, diff = git("diff", "--name-only", "--no-renames", "HEAD")
    return [f for f in diff.splitlines() if f.strip()] + untracked()


def changed_files(mb: str) -> list[str]:
    """Files touched since the merge-base: --no-renames also reports the source path of a rename."""
    _, diff = git("diff", "--name-only", "--no-renames", mb)
    return sorted({f for f in diff.splitlines() if f.strip()} | set(untracked()))


def added_files(mb: str) -> list[str]:
    _, diff = git("diff", "--name-only", "--no-renames", "--diff-filter=A", mb)
    return [f for f in diff.splitlines() if f.strip()] + untracked()


def from_base(mb: str, path: str) -> str | None:
    """Content of the file at the merge-base, None if it does not exist there."""
    code, text = git("show", f"{mb}:{normalize(path)}")
    return text if code == 0 else None


def branch_commits(mb: str) -> list[tuple[str, str | None, list[str]]]:
    """(sha, task of the Test-Lock trailer or None, files touched) from oldest to newest."""
    _, shas = git("rev-list", "--reverse", f"{mb}..HEAD")
    out = []
    for sha in shas.split():
        _, body = git("show", "-s", "--format=%B", sha)
        _, files = git("diff-tree", "--no-commit-id", "--name-only", "--no-renames", "-r", "--root", sha)
        m = TEST_LOCK.search(body)
        out.append((sha, m.group(1) if m else None, [f for f in files.splitlines() if f.strip()]))
    return out


def voided_approvals(commits: list[tuple[str, str | None, list[str]]], tasks: str) -> list[str]:
    """Test approvals that no longer match the latest Test-Lock commit of their task."""
    err = []
    for tid, sha in spec_lint.test_approvals(tasks).items():
        if sha is None:
            continue
        pos = next((i for i, (c, lock, _) in enumerate(commits) if c.startswith(sha)), None)
        if pos is None or commits[pos][1] != tid:
            err.append(f"{tid}: the approved SHA {sha} is not a 'Test-Lock: {tid}' commit of this branch "
                       "(rebase or amend?)")
        elif any(lock == tid for _, lock, _ in commits[pos + 1:]):
            err.append(f"{tid}: new Test-Lock commit after the approval ({sha}): the tests must be approved again")
    return err


def locked_tests(commits: list[tuple[str, str | None, list[str]]], dirty: list[str]):
    """Return (locked files, violations, non-test files in Test-Lock commits)."""
    locked: set[str] = set()
    violations, non_test = [], []
    for sha, lock, files in commits:
        if lock:
            for f in files:
                if is_test(f):
                    locked.add(f)
                else:
                    non_test.append(f"{f} ({sha[:7]})")
            continue
        violations += [f"{f} (commit {sha[:7]})" for f in files if f in locked]
    violations += [f"{f} (uncommitted)" for f in dirty if f in locked]
    return sorted(locked), violations, non_test


def level_problems(feature: Path, changed: list[str], agents: str, spec_at_base: str | None = None):
    """(declared level, errors if the diff requires a higher level). The spec at the merge-base wins, if present."""
    spec = feature / "spec.md"
    text = spec_at_base if spec_at_base is not None else (spec.read_text(encoding="utf-8") if spec.is_file() else "")
    declared = spec_lint.level(text)
    required, reasons = required_level(changed, agents)
    if ORDER[required] > ORDER[declared]:
        return declared, [f"level underestimated: the spec declares {declared}, the diff requires at least "
                          f"{required} ({'; '.join(reasons)}). Update the level and get the spec re-approved"]
    return declared, []


def new_adrs(added: list[str]) -> list[str]:
    return [f for f in added if normalize(f).startswith("docs/adr/") and f.lower().endswith(".md")
            and not normalize(f).split("/")[-1].lower().startswith(("readme", "index", "template"))]


def planned(f: str, plan: list[str]) -> bool:
    """In the plan, or a lockfile whose manifest (in the same folder) is in the plan."""
    if any(matches(f, p) for p in plan):
        return True
    folder, _, name = normalize(f).rpartition("/")
    manifest = LOCKFILE.get(name)
    return bool(manifest) and any(matches(f"{folder}/{manifest}" if folder else manifest, p) for p in plan)


def undecided_dependencies(changed: list[str], plan: list[str], added: list[str] | None = None) -> list[str]:
    """Changed manifests the plan does not list, if the diff adds no ADR."""
    if new_adrs(added or []):
        return []
    return [f for f in changed if is_manifest(f) and not planned(f, plan)]


def analyze(feature: Path, changed: list[str], agents: str):
    plan = plan_paths((feature / "plan.md").read_text(encoding="utf-8")) if (feature / "plan.md").is_file() else []
    forbidden = forbidden_paths(agents)
    allowed = ALWAYS_ALLOWED + (f"docs/specs/{feature.name}/",)
    violations = [f for f in changed if any(matches(f, v) for v in forbidden)]
    outside = [f for f in changed
               if f not in violations and not f.startswith(allowed) and not any(matches(f, p) for p in plan)]
    untouched = [p for p in plan if not any(matches(f, p) for f in changed)]
    return plan, violations, outside, untouched


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if not args:
        print(__doc__)
        return 2
    strict = "--strict" in argv
    base_arg = argv[argv.index("--base") + 1] if "--base" in argv else None
    if base_arg is not None and base_arg in args:
        args.remove(base_arg)
    feature = Path(args[0])
    if not feature.is_dir():
        print(f"[ERROR] folder not found: {feature}")
        return 2
    if git("rev-parse", "--is-inside-work-tree")[0] != 0:
        print("[ERROR] not a git repository")
        return 2
    base = base_ref(base_arg)
    if base is None:
        print("[ERROR] no base ref found: use --base <ref>")
        return 2
    try:
        mb = merge_base(base)
    except RuntimeError as e:
        print(f"[ERROR] {e}")
        return 2
    changed = changed_files(mb)
    agents = from_base(mb, "AGENTS.md")  # the branch cannot loosen forbidden zones and sensitive areas
    if agents is None:
        agents = Path("AGENTS.md").read_text(encoding="utf-8") if Path("AGENTS.md").is_file() else ""
    plan, violations, outside, untouched = analyze(feature, changed, agents)
    level, underestimated = level_problems(feature, changed, agents, from_base(mb, f"{feature.as_posix()}/spec.md"))
    if level == "S" and not plan:
        outside = []  # level S: no plan to compare with
    commits = branch_commits(mb)
    locked, touched_tests, non_test = locked_tests(commits, uncommitted())
    tasks_p = feature / "tasks.md"
    voided = voided_approvals(commits, tasks_p.read_text(encoding="utf-8")) if tasks_p.is_file() else []
    print(f"Base: {base}; level: {level}; changed files: {len(changed)}; paths in the plan: {len(plan)}; "
          f"locked tests: {len(locked)}")
    if level == "S" and not plan:
        print("[INFO] level S without a plan: plan comparison skipped")
    elif not plan:
        print("[WARN] no path extracted from plan.md: the plan comparison is not reliable")
    if "AGENTS.md" in changed:
        print("[WARN] AGENTS.md changed in the branch: forbidden zones and sensitive areas read from the base version")
    for v in non_path_entries(agents):
        print(f"[WARN] AGENTS.md entry that does not look like a path, ignored: '{v}' (use `path/` in backticks)")
    for e in underestimated:
        print(f"[ERROR] {e}")
    for w in size_warnings(changed, level):
        print(f"[WARN] {w}")
    if not underestimated and ORDER[level] > ORDER[required_level(changed, agents)[0]]:
        print(f"[INFO] level {level} declared; the hard criteria of this diff would allow "
              f"{required_level(changed, agents)[0]}")
    dependencies = undecided_dependencies(changed, plan, added_files(mb))
    for f in dependencies:
        print(f"[ERROR] dependencies changed without plan or ADR: {f} (new dependencies only in the approved plan or "
              "with a new ADR in docs/adr/)")
    for e in voided:
        print(f"[ERROR] tests approved: {e}")
    for f in violations:
        print(f"[ERROR] file in a forbidden zone (AGENTS.md): {f}")
    for f in touched_tests:
        print(f"[ERROR] locked test (Test-Lock) changed after locking: {f}")
    for f in non_test:
        print(f"[WARN] non-test file in a Test-Lock commit, not locked: {f}")
    for f in outside:
        print(f"[{'ERROR' if strict else 'WARN'}] file outside the plan: {f}")
    for p in untouched:
        print(f"[INFO] in the plan but not touched: {p}")
    ko = (bool(violations) or bool(touched_tests) or bool(underestimated) or bool(dependencies) or bool(voided)
          or (strict and bool(outside)))
    print("SCOPE: " + ("OK" if not ko else "VIOLATIONS"))
    return 1 if ko else 0


if __name__ == "__main__":
    for stream in (sys.stdout, sys.stderr):  # UTF-8 even with a cp1252 console (Windows)
        stream.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main(sys.argv[1:]))
